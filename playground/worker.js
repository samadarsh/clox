// Runs clox in a Web Worker, so a long or endless program never blocks the
// page. The page stops a program by terminating this worker and starting a
// new one: a busy worker can't be interrupted any other way, because
// clox_run() never returns control to JavaScript until the program ends.
//
// Messages from the page:  {type: "run", source}
// Messages to the page:    {type: "ready"}
//                          {type: "output", chunks: [[stream, text], ...]}
//                            stream is "out" (print) or "err" (errors)
//                          {type: "done", exitCode, ms}
//                          {type: "crash", message}

importScripts("clox.js"); // defines createClox(), generated by `make wasm`

// Download and compile clox.wasm once. Every run then makes a new *instance*
// of it: new memory, so a fresh VM with nothing left over from the last run.
// (Fetching the bytes first, instead of compileStreaming, works with any web
// server: streaming needs the server to label .wasm as application/wasm.)
const compiled = fetch("clox.wasm")
  .then((response) => {
    if (!response.ok) throw new Error(`HTTP ${response.status}`);
    return response.arrayBuffer();
  })
  .then((bytes) => WebAssembly.compile(bytes));

// Output is sent in batches: a message per printed line would flood the page
// when a program prints in a tight loop.
const FLUSH_MS = 50;
const MAX_OUTPUT_CHARS = 1_000_000;
let pending = [];
let lastFlush = 0;
let sentChars = 0;
let truncated = false;

function flush() {
  if (pending.length > 0) {
    postMessage({ type: "output", chunks: pending });
    pending = [];
  }
  lastFlush = performance.now();
}

function emit(stream, line) {
  if (truncated) return;
  sentChars += line.length + 1;
  if (sentChars > MAX_OUTPUT_CHARS) {
    truncated = true;
    pending.push(["err", "[output truncated after 1,000,000 characters]"]);
  } else {
    pending.push([stream, line]);
  }
  if (performance.now() - lastFlush > FLUSH_MS) flush();
}

async function run(source) {
  pending = [];
  sentChars = 0;
  truncated = false;
  lastFlush = performance.now();

  const module = await compiled;
  const clox = await createClox({
    // Hand Emscripten the already-compiled module instead of letting it fetch.
    instantiateWasm(imports, done) {
      WebAssembly.instantiate(module, imports).then((instance) => done(instance, module));
      return {};
    },
    print: (line) => emit("out", line),
    printErr: (line) => emit("err", line),
  });

  // Copy the program into the module's memory as a '\0'-terminated UTF-8
  // string. stringToNewUTF8 allocates it with the module's malloc, so free
  // it with the module's free when clox is done with it.
  const start = performance.now();
  const ptr = clox.stringToNewUTF8(source);
  let exitCode;
  try {
    exitCode = clox._clox_run(ptr);
  } finally {
    clox._free(ptr);
  }
  const ms = performance.now() - start;

  flush();
  postMessage({ type: "done", exitCode, ms });
}

onmessage = (event) => {
  if (event.data.type !== "run") return;
  run(event.data.source).catch((error) => {
    flush();
    // clox calls exit(1) if memory runs out; Emscripten turns that into an
    // exception. Anything else here is a bug in the playground itself.
    postMessage({ type: "crash", message: String(error && error.message || error) });
  });
};

compiled.then(
  () => postMessage({ type: "ready" }),
  (error) => postMessage({ type: "crash", message: "Could not load clox.wasm: " + error }),
);
