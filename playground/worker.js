// Runs clox in a Web Worker, so a long or endless program never blocks the
// page. The page stops a program by terminating this worker and starting a
// new one: a busy worker can't be interrupted any other way, because the C
// functions never return control to JavaScript until the program ends.
//
// Messages from the page (each has an `id`, echoed in the replies):
//   {type: "run", id, source}          run normally
//   {type: "debug", id, source, limit} run while recording up to `limit` steps
//   {type: "disassemble", id, source}  compile only, return the bytecode
// Messages to the page:
//   {type: "ready"}
//   {type: "output", id, chunks: [[stream, text], ...]}   stream: "out"/"err"
//   {type: "done", id, exitCode, ms, stats}               after run or debug
//   {type: "recording", id, recording, full}              after debug
//   {type: "bytecode", id, exitCode, functions, errors}   after disassemble
//   {type: "crash", id, message}

importScripts("clox.js"); // defines createClox(), generated by `make wasm`

// Download and compile clox.wasm once. Every request then makes a new
// *instance* of it: new memory, so a fresh VM with nothing left over.
// (Fetching the bytes first, instead of compileStreaming, works with any web
// server: streaming needs the server to label .wasm as application/wasm.)
const compiled = fetch("clox.wasm")
  .then((response) => {
    if (!response.ok) throw new Error(`HTTP ${response.status}`);
    return response.arrayBuffer();
  })
  .then((bytes) => WebAssembly.compile(bytes));

// Output is sent in batches: a message per printed line would flood the page
// when a program prints in a tight loop.
const FLUSH_MS = 50;
const MAX_OUTPUT_CHARS = 1_000_000;

function makeOutput(id) {
  let pending = [];
  let lastFlush = performance.now();
  let sent = 0;
  let truncated = false;
  return {
    flush() {
      if (pending.length > 0) postMessage({ type: "output", id, chunks: pending });
      pending = [];
      lastFlush = performance.now();
    },
    emit(stream, line) {
      if (truncated) return;
      sent += line.length + 1;
      if (sent > MAX_OUTPUT_CHARS) {
        truncated = true;
        pending.push(["err", "[output truncated after 1,000,000 characters]"]);
      } else {
        pending.push([stream, line]);
      }
      if (performance.now() - lastFlush > FLUSH_MS) this.flush();
    },
  };
}

// A new instance of clox. `options.print`/`printErr` receive whole lines.
// The options object becomes the instance's `Module`, so `printedLines` is
// readable from C (clox_wasm.c uses it to note, at each recorded step, how
// much output the program had printed).
async function newClox(print, printErr) {
  const module = await compiled;
  const options = {
    printedLines: 0,
    // Hand Emscripten the already-compiled module instead of letting it fetch.
    instantiateWasm(imports, done) {
      WebAssembly.instantiate(module, imports).then((instance) => done(instance, module));
      return {};
    },
    print(line) {
      options.printedLines++;
      print(line);
    },
    printErr,
  };
  return createClox(options);
}

// Copies `source` into the instance's memory as a '\0'-terminated UTF-8
// string (allocated with the instance's malloc), calls `fn` with its address,
// and frees it again.
function withSource(clox, source, fn) {
  const ptr = clox.stringToNewUTF8(source);
  try {
    return fn(ptr);
  } finally {
    clox._free(ptr);
  }
}

async function run(id, source) {
  const out = makeOutput(id);
  const clox = await newClox((l) => out.emit("out", l), (l) => out.emit("err", l));
  const start = performance.now();
  const exitCode = withSource(clox, source, (ptr) => clox._clox_run(ptr));
  const ms = performance.now() - start;
  out.flush();
  postMessage({ type: "done", id, exitCode, ms, stats: stats(clox) });
}

async function debug(id, source, limit) {
  const out = makeOutput(id);
  const clox = await newClox((l) => out.emit("out", l), (l) => out.emit("err", l));
  const start = performance.now();
  const exitCode = withSource(clox, source, (ptr) => clox._clox_debug(ptr, limit));
  const ms = performance.now() - start;
  out.flush();
  const full = clox._clox_recording_full() === 1;
  const recording = JSON.parse(clox.UTF8ToString(clox._clox_recording()));
  postMessage({ type: "recording", id, recording, full });
  postMessage({ type: "done", id, exitCode, ms, stats: stats(clox), recorded: true, full });
}

async function disassemble(id, source) {
  const lines = [];
  const errors = [];
  const clox = await newClox((l) => lines.push(l), (l) => errors.push(l));
  const exitCode = withSource(clox, source, (ptr) => clox._clox_disassemble(ptr));
  postMessage({ type: "bytecode", id, exitCode, functions: parseBytecode(lines), errors });
}

// Turns clox_disassemble()'s output into
//   [{name, ops: [{offset, line, text}]}]
// "@fn name" starts a function; "@op offset line" starts an instruction,
// and the disassembler's line(s) that follow are its text.
function parseBytecode(lines) {
  const functions = [];
  let fn = null;
  let op = null;
  for (const line of lines) {
    if (line.startsWith("@fn ")) {
      fn = { name: line.slice(4), ops: [] };
      functions.push(fn);
    } else if (line.startsWith("@op ")) {
      const [offset, sourceLine] = line.slice(4).split(" ").map(Number);
      op = { offset, line: sourceLine, text: [] };
      fn.ops.push(op);
    } else if (op) {
      op.text.push(line);
    }
  }
  for (const f of functions) for (const o of f.ops) o.text = o.text.join("\n");
  return functions;
}

function stats(clox) {
  return {
    instructions: clox._clox_stat_instructions(),
    collections: clox._clox_stat_collections(),
    peakBytes: clox._clox_stat_peak_bytes(),
  };
}

onmessage = (event) => {
  const { type, id, source, limit } = event.data;
  const task =
    type === "run" ? run(id, source) :
    type === "debug" ? debug(id, source, limit) :
    type === "disassemble" ? disassemble(id, source) : null;
  if (!task) return;
  task.catch((error) => {
    // clox calls exit(1) if memory runs out; Emscripten turns that into an
    // exception. Anything else here is a bug in the playground itself.
    postMessage({ type: "crash", id, message: String((error && error.message) || error) });
  });
};

compiled.then(
  () => postMessage({ type: "ready" }),
  (error) => postMessage({ type: "crash", message: "Could not load clox.wasm: " + error }),
);
